I18nLocale i18n_locale(const char *locale) {
  if (!locale) return I18N_LOCALE_EN;
  if (locale[0] == 'd' && locale[1] == 'e') return I18N_LOCALE_DE;
  if (locale[0] == 'f' && locale[1] == 'r') return I18N_LOCALE_FR;
  if (locale[0] == 'e' && locale[1] == 's') return I18N_LOCALE_ES;
  if (locale[0] == 'i' && locale[1] == 't') return I18N_LOCALE_IT;
  if (locale[0] == 'p' && locale[1] == 't') return I18N_LOCALE_PT;
  if ((locale[0] == 'z' && locale[1] == 'h') || (locale[0] == 'e' && locale[1] == 'n')) {
    const char *region = strchr(locale, '_');
    if (!region) region = strchr(locale, '-');
    if (region && region[1] == 'T' && region[2] == 'W') return I18N_LOCALE_ZH_TW;
    if (region && region[1] == 'C' && region[2] == 'N') return I18N_LOCALE_ZH_CN;
  }
  return I18N_LOCALE_EN;
}

void i18n_set_locale(I18nLocale locale) {
  s_locale = locale < I18N_LOCALE_COUNT ? locale : I18N_LOCALE_EN;
}

I18nLocale i18n_current_locale(void) {
  return s_locale;
}

const char *i18n_text(I18nString id) {
  if (id >= I18N_STRING_COUNT) return "";
  const char *value = s_catalog[s_locale][id];
  return value ? value : s_catalog[I18N_LOCALE_EN][id];
}

bool i18n_catalog_complete(void) {
  for (size_t locale = 0; locale < I18N_LOCALE_COUNT; locale++) {
    for (size_t id = 0; id < I18N_STRING_COUNT; id++) {
      const char *value =
          s_catalog[locale][id] ? s_catalog[locale][id] : s_catalog[I18N_LOCALE_EN][id];
      if (!value || !value[0]) return false;
    }
  }
  return true;
}

bool i18n_uses_decimal_comma(void) {
  return s_locale == I18N_LOCALE_DE || s_locale == I18N_LOCALE_FR || s_locale == I18N_LOCALE_ES ||
         s_locale == I18N_LOCALE_IT || s_locale == I18N_LOCALE_PT;
}
